const COVERED_UNTIL = '2027-12-31';

let warned = false;
function warnCoverage(ymd) {
  if (warned || ymd <= COVERED_UNTIL) return;
  warned = true;
  console.warn(`⚠️ [kr-business-days] 공휴일 목록이 ${COVERED_UNTIL}까지만 있음(요청 ${ymd}). ops/lib/kr-business-days.js에 다음 해 공휴일을 추가하세요.`);
}

/** 'YYYY-MM-DD'가 영업일(평일 & 공휴일 아님)인지 */
function isBizDay(ymd) {
  warnCoverage(ymd);
  const dow = new Date(ymd + 'T00:00:00Z').getUTCDay();
  return dow !== 0 && dow !== 6 && !HOLIDAYS[ymd];
}

/** ymd 기준 n 영업일 뒤. n=0이면 ymd 그대로(긴급 건은 주말이라도 당일). */
function addBizDays(ymd, n) {
  const d = new Date(ymd + 'T00:00:00Z');
  const step = () => { d.setUTCDate(d.getUTCDate() + 1); return d.toISOString().slice(0, 10); };
  let cur = ymd;
  let left = n;
  while (left > 0) {
    cur = step();
    if (isBizDay(cur)) left--;
  }
  return cur;
}

